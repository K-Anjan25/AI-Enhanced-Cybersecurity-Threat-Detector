"""Retention against a real PostgreSQL: the catalog, the partition runner and the sweep.

These skip unless ``AEGIS_DATABASE_URL`` names a running PostgreSQL, for the reason
``test_migration_live.py`` gives: partition catalogs and ``DROP TABLE`` behave only as
they do on a server. Each test runs in its own temporary schema with minimal tables of
the same shape (partitioned by month, and ``id``/``timestamp`` for the swept tables), so
the tests do not depend on the full migration and leave nothing behind.

To run them locally::

    python -c "import pgserver; print(pgserver.get_server('/tmp/pgdata').get_uri())"
    AEGIS_DATABASE_URL=postgresql+psycopg://... pytest tests/test_retention_live.py
"""

from __future__ import annotations

import os
import uuid
from collections.abc import Iterator
from datetime import UTC, datetime, timedelta

import pytest

_URL = os.environ.get("AEGIS_DATABASE_URL", "")

pytestmark = pytest.mark.skipif(
    not _URL.startswith("postgresql"),
    reason="AEGIS_DATABASE_URL is not set to a PostgreSQL server; these tests need a real one",
)


@pytest.fixture
def schema_engine() -> Iterator[object]:
    """An engine whose connections search a fresh schema holding minimal tables."""
    import sqlalchemy as sa

    schema = f"ret_{uuid.uuid4().hex[:12]}"
    admin = sa.create_engine(_URL)
    with admin.begin() as conn:
        conn.exec_driver_sql(f"CREATE SCHEMA {schema}")
    engine = sa.create_engine(_URL, connect_args={"options": f"-csearch_path={schema}"})
    try:
        with engine.begin() as conn:
            for table in ("alerts", "ingest_stats"):
                conn.exec_driver_sql(
                    f"CREATE TABLE {table} (id bigint, created_at timestamptz NOT NULL, "
                    "PRIMARY KEY (id, created_at)) PARTITION BY RANGE (created_at)"
                )
            for table in ("log_events", "flow_events"):
                conn.exec_driver_sql(
                    f"CREATE TABLE {table} (id bigint GENERATED BY DEFAULT AS IDENTITY "
                    "PRIMARY KEY, timestamp timestamptz NOT NULL)"
                )
        yield engine
    finally:
        engine.dispose()
        with admin.begin() as conn:
            conn.exec_driver_sql(f"DROP SCHEMA {schema} CASCADE")
        admin.dispose()


def _make_partition(engine: object, table: str, year: int, month: int) -> None:
    from app.db.partitions import create_partition_sql

    with engine.begin() as conn:  # type: ignore[attr-defined]
        conn.exec_driver_sql(create_partition_sql(table, year, month))


def test_the_catalog_lists_exactly_the_monthly_partitions_that_exist(schema_engine: object) -> None:
    from app.services.retention_catalog import list_partitions

    _make_partition(schema_engine, "alerts", 2026, 3)
    _make_partition(schema_engine, "alerts", 2026, 4)
    _make_partition(schema_engine, "ingest_stats", 2026, 3)

    assert list_partitions(schema_engine) == {  # type: ignore[arg-type]
        ("alerts", 2026, 3),
        ("alerts", 2026, 4),
        ("ingest_stats", 2026, 3),
    }


def test_the_catalog_refuses_a_partition_it_cannot_plan(schema_engine: object) -> None:
    """A partition with a name retention does not understand would survive every run."""
    from app.services.retention_catalog import list_partitions

    with schema_engine.begin() as conn:  # type: ignore[attr-defined]
        conn.exec_driver_sql(
            "CREATE TABLE alerts_scratch PARTITION OF alerts "
            "FOR VALUES FROM ('2026-05-01') TO ('2026-06-01')"
        )

    with pytest.raises(ValueError, match="does not follow"):
        list_partitions(schema_engine)  # type: ignore[arg-type]


def test_the_runner_drops_a_partition_once_and_reports_the_second_run_as_absent(
    schema_engine: object,
) -> None:
    import sqlalchemy as sa
    from app.db.partitions import drop_partition_sql
    from app.services.retention_catalog import CatalogRunner, list_partitions

    _make_partition(schema_engine, "alerts", 2026, 3)
    runner = CatalogRunner(schema_engine)  # type: ignore[arg-type]
    statement = drop_partition_sql("alerts", 2026, 3)

    assert runner(statement) is True
    assert list_partitions(schema_engine) == set()  # type: ignore[arg-type]
    assert runner(statement) is False  # the second run: already gone, nothing changed

    # The table itself survives: retention drops months, never the parent.
    with schema_engine.connect() as conn:  # type: ignore[attr-defined]
        exists = conn.execute(sa.text("SELECT to_regclass('alerts') IS NOT NULL")).scalar_one()
    assert exists is True


@pytest.mark.parametrize(
    "statement",
    [
        "DROP TABLE alerts",
        "DROP TABLE users_2026_03",
        "DELETE FROM alerts WHERE created_at < now()",
        "DROP TABLE IF EXISTS alerts_2026_03; DROP TABLE users",
    ],
)
def test_the_runner_refuses_anything_but_a_retention_partition_drop(
    schema_engine: object, statement: str
) -> None:
    from app.services.retention_catalog import CatalogRunner

    with pytest.raises(ValueError, match="refusing"):
        CatalogRunner(schema_engine)(statement)  # type: ignore[arg-type]


def test_the_sweep_deletes_only_expired_rows_in_bounded_batches(schema_engine: object) -> None:
    from app.services.retention_catalog import sweep_expired_rows

    now = datetime.now(UTC)
    old = [now - timedelta(days=40 + i) for i in range(3)]
    fresh = [now - timedelta(days=1), now]
    with schema_engine.begin() as conn:  # type: ignore[attr-defined]
        for when in old + fresh:
            conn.exec_driver_sql("INSERT INTO log_events (timestamp) VALUES (%s)", (when,))
        conn.exec_driver_sql("INSERT INTO flow_events (timestamp) VALUES (%s)", (old[0],))

    cutoff = now - timedelta(days=30)
    # batch_rows=2 forces more than one transaction for three expired rows.
    deleted = sweep_expired_rows(schema_engine, cutoff=cutoff, batch_rows=2)  # type: ignore[arg-type]

    assert deleted == {"log_events": 3, "flow_events": 1}
    with schema_engine.connect() as conn:  # type: ignore[attr-defined]
        left = conn.exec_driver_sql("SELECT count(*) FROM log_events").scalar_one()
    assert left == 2
    # A second sweep finds nothing: idempotent, like the partition drop.
    assert sweep_expired_rows(schema_engine, cutoff=cutoff, batch_rows=2) == {  # type: ignore[arg-type]
        "log_events": 0,
        "flow_events": 0,
    }
